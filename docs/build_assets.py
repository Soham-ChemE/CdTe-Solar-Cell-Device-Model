"""Build the data and preview assets of the live page (docs/index.html) from the committed CSVs.

Writes
  docs/assets/data.js            window.CDTE = {...}: the identifiability profile (hero) and the fine Delta-chi2 scan (3D valley)
  docs/assets/social-preview.png 1280x640 card for the repository's social preview
Run from anywhere:  python docs/build_assets.py   (numpy, matplotlib)
"""
import csv
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

REPO = Path(__file__).resolve().parents[1]
IDENT = REPO / "optionA/sesame/kujovic/ident"
OUT = REPO / "docs/assets"
OUT.mkdir(parents=True, exist_ok=True)


def rows(p):
    with open(p, newline="") as fh:
        return list(csv.DictReader(fh))


summary = rows(IDENT / "ident_summary.csv")[0]
ridge = {round(float(r["dEc"]), 3): float(r["logS"]) for r in rows(IDENT / "ridge_points.csv")}
profile = []
for r in rows(IDENT / "ident_profile.csv"):
    d = round(float(r["dEc"]), 3)
    profile.append(dict(dEc=d, logS=ridge[d], dchi2=round(float(r["dchi2_sim_phi0.50"]), 1),
                        voc=round(float(r["Voc300_sim_phi0.50"]), 1), ff=round(float(r["FF300_sim_phi0.50"]), 2)))
profile.sort(key=lambda p: -p["dEc"])

fine = rows(IDENT / "ident_fine_scan.csv")
chi_min = min(float(r["chi2"]) for r in fine)
valley = {}
for i, r in enumerate(fine):
    d = round(float(r["dEc"]), 3)
    valley.setdefault(d, []).append([round(float(r["logS"]), 4), round(float(r["chi2"]) - chi_min, 2)])
for d in valley:  # keep every second point of each 241-point scan, plus the last
    pts = sorted(valley[d])
    valley[d] = pts[::2] + ([pts[-1]] if len(pts) % 2 == 0 else [])
data = dict(
    source="optionA/sesame/kujovic/ident/ (ident_profile.csv, ridge_points.csv, ident_fine_scan.csv, ident_summary.csv)",
    chi2_min=float(summary["chi2_min"]), dof=int(summary["dof"]),
    best=dict(dEc=float(summary["best_cliff_dEc"]), logS=ridge[round(float(summary["best_cliff_dEc"]), 3)]),
    ci95=[float(summary["dEc_95_lo"]), float(summary["dEc_95_hi"])], xps=[-0.32, -0.22],
    voc_measured=875.5, profile=profile,
    valley=[dict(dEc=d, pts=valley[d]) for d in sorted(valley)],
)
js = "// Generated by docs/build_assets.py from optionA/sesame/kujovic/ident/*.csv. Do not edit by hand.\n"
js += "window.CDTE = " + json.dumps(data, separators=(",", ":")) + ";\n"
(OUT / "data.js").write_text(js)
print("wrote", OUT / "data.js", len(js), "bytes")

